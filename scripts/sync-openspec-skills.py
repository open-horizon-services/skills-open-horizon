#!/usr/bin/env python3
"""Synchronize the upstream OpenSpec skill bundle without overwriting local edits."""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path, PurePosixPath


ALIASES = {
    "openspec-apply-change": ("opsx-apply", "opsx:apply"),
    "openspec-archive-change": ("opsx-archive", "opsx:archive"),
    "openspec-bulk-archive-change": ("opsx-bulk-archive", "opsx:bulk-archive"),
    "openspec-continue-change": ("opsx-continue", "opsx:continue"),
    "openspec-explore": ("opsx-explore", "opsx:explore"),
    "openspec-ff-change": ("opsx-ff", "opsx:ff"),
    "openspec-new-change": ("opsx-new", "opsx:new"),
    "openspec-onboard": ("opsx-onboard", "opsx:onboard"),
    "openspec-propose": ("opsx-propose", "opsx:propose"),
    "openspec-sync-specs": ("opsx-sync", "opsx:sync"),
    "openspec-update-change": ("opsx-update", "opsx:update"),
    "openspec-verify-change": ("opsx-verify", "opsx:verify"),
}
COMMAND_REFERENCE = re.compile(r"`(/openspec-[a-z-]+)([^`]*)`")
MANIFEST_HEADER = "# Managed OpenSpec skill files; generated by sync-openspec-skills.py"


def digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def valid_relative_path(value: str) -> bool:
    path = PurePosixPath(value)
    return (
        not path.is_absolute()
        and bool(path.parts)
        and path.parts[0].startswith("openspec-")
        and all(part not in {"", ".", ".."} for part in path.parts)
    )


def translate_skill_commands(path: str, content: bytes) -> tuple[bytes | None, list[str]]:
    if PurePosixPath(path).name != "SKILL.md":
        return content, []

    text = content.decode("utf-8")
    unknown: list[str] = []

    def replace(match: re.Match[str]) -> str:
        command = match.group(1).lstrip("/")
        aliases = ALIASES.get(command)
        if aliases is None:
            unknown.append(command)
            return match.group(0)
        bob, claude = aliases
        suffix = match.group(2)
        return f"`Bob: /{bob}{suffix}; Claude Code: /{claude}{suffix}`"

    translated = COMMAND_REFERENCE.sub(replace, text)
    if unknown:
        return None, sorted(set(unknown))
    return translated.encode("utf-8"), []


def load_manifest(path: Path) -> tuple[str, dict[str, str]]:
    if not path.exists():
        return "", {}

    source_commit = ""
    files: dict[str, str] = {}
    for line_number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        if not line or line.startswith("#"):
            continue
        if line.startswith("source_commit "):
            source_commit = line.removeprefix("source_commit ").strip()
            continue
        fields = line.split("  ", 1)
        if len(fields) != 2 or not valid_relative_path(fields[1]):
            raise ValueError(f"Invalid manifest entry at {path}:{line_number}")
        file_hash, relative_path = fields
        if not re.fullmatch(r"[0-9a-f]{64}", file_hash):
            raise ValueError(f"Invalid SHA-256 hash at {path}:{line_number}")
        files[relative_path] = file_hash
    return source_commit, files


def render_manifest(source_commit: str, files: dict[str, str]) -> str:
    lines = [MANIFEST_HEADER, f"source_commit {source_commit}"]
    lines.extend(f"{files[path]}  {path}" for path in sorted(files))
    return "\n".join(lines) + "\n"


def collect_upstream_files(
    upstream_root: Path,
) -> tuple[dict[str, bytes], list[str], set[str]]:
    files: dict[str, bytes] = {}
    conflicts: list[str] = []
    blocked_paths: set[str] = set()
    if not upstream_root.is_dir():
        raise ValueError(f"Upstream skills directory does not exist: {upstream_root}")

    for skill_dir in sorted(upstream_root.iterdir()):
        if not skill_dir.name.startswith("openspec-"):
            continue
        if skill_dir.is_symlink():
            conflicts.append(f"{skill_dir.name}: upstream skill directory is a symbolic link")
            blocked_paths.add(f"{skill_dir.name}/")
            continue
        if not skill_dir.is_dir():
            continue

        for path in sorted(skill_dir.rglob("*")):
            relative = path.relative_to(upstream_root).as_posix()
            if not valid_relative_path(relative):
                conflicts.append(f"{relative}: unsafe upstream path")
                continue
            if path.is_symlink():
                conflicts.append(f"{relative}: upstream symbolic links are not imported")
                blocked_paths.add(relative)
                continue
            if path.is_file():
                content, unknown = translate_skill_commands(relative, path.read_bytes())
                if unknown:
                    conflicts.append(
                        f"{relative}: no Bob/Claude command mapping for "
                        + ", ".join(f"/{command}" for command in unknown)
                    )
                    blocked_paths.add(relative)
                elif content is not None:
                    files[relative] = content
    return files, conflicts, blocked_paths


def safe_destination(skills_root: Path, relative: str) -> tuple[Path | None, str | None]:
    if not valid_relative_path(relative):
        return None, f"{relative}: unsafe managed path"

    destination = skills_root
    for component in PurePosixPath(relative).parts:
        destination = destination / component
        if destination.is_symlink():
            return None, f"{relative}: destination path contains a symbolic link"
        if destination.exists() and destination != skills_root / relative:
            if not destination.is_dir():
                return None, f"{relative}: destination parent is not a directory"
    return destination, None


def remove_empty_skill_directories(path: Path, skills_root: Path) -> None:
    current = path.parent
    while current != skills_root and current.is_relative_to(skills_root):
        try:
            current.rmdir()
        except OSError:
            return
        current = current.parent


def write_report(
    report_path: Path | None,
    source_commit: str,
    added: list[str],
    updated: list[str],
    removed: list[str],
    conflicts: list[str],
) -> str:
    sections = [
        "## OpenSpec skill synchronization",
        "",
        f"- Upstream: `Fission-AI/OpenSpec` `main/skills/` at `{source_commit}`",
    ]
    for title, paths in (
        ("Added", added),
        ("Updated", updated),
        ("Removed as stale upstream-managed files", removed),
    ):
        sections.extend(["", f"### {title}"])
        if paths:
            sections.extend(f"- `{path}`" for path in paths)
        else:
            sections.append("- None")
    sections.extend(["", "### Conflicts and skipped cleanup"])
    if conflicts:
        sections.extend(f"- {conflict}" for conflict in conflicts)
    else:
        sections.append("- None")
    report = "\n".join(sections) + "\n"
    if report_path is not None:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(report, encoding="utf-8")
    return report


def synchronize(
    repository_root: Path,
    upstream_root: Path,
    source_commit: str,
    report_path: Path | None = None,
) -> tuple[bool, str]:
    if not re.fullmatch(r"[0-9a-f]{40}", source_commit):
        raise ValueError("Upstream commit must be a full 40-character lowercase SHA")

    skills_root = repository_root / ".agents" / "skills"
    manifest_path = repository_root / ".github" / "openspec-skills-manifest.txt"
    if (repository_root / ".agents").is_symlink() or skills_root.is_symlink():
        raise ValueError("The canonical .agents/skills path must not be a symbolic link")
    if (repository_root / ".github").is_symlink() or manifest_path.is_symlink():
        raise ValueError("The upstream manifest path must not be a symbolic link")
    skills_root.mkdir(parents=True, exist_ok=True)

    previous_commit, previous_files = load_manifest(manifest_path)
    upstream_files, conflicts, blocked_paths = collect_upstream_files(upstream_root)
    next_files: dict[str, str] = {}
    added: list[str] = []
    updated: list[str] = []
    removed: list[str] = []
    content_changed = False

    for relative, content in sorted(upstream_files.items()):
        destination, path_error = safe_destination(skills_root, relative)
        if path_error:
            conflicts.append(path_error)
            if relative in previous_files:
                next_files[relative] = previous_files[relative]
            continue
        assert destination is not None

        expected_hash = digest(content)
        previous_hash = previous_files.get(relative)
        current_hash = digest(destination.read_bytes()) if destination.is_file() else None

        if destination.exists() and not destination.is_file():
            conflicts.append(f"{relative}: destination exists but is not a regular file")
            if previous_hash:
                next_files[relative] = previous_hash
            continue
        if current_hash == expected_hash:
            next_files[relative] = expected_hash
            continue
        if current_hash is None and previous_hash is not None:
            conflicts.append(f"{relative}: locally removed managed file was not restored")
            next_files[relative] = previous_hash
            continue
        if current_hash is not None and previous_hash is None:
            conflicts.append(f"{relative}: untracked local file was preserved")
            continue
        if current_hash is not None and current_hash != previous_hash:
            conflicts.append(f"{relative}: locally modified file was preserved")
            next_files[relative] = previous_hash or current_hash
            continue

        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(content)
        next_files[relative] = expected_hash
        content_changed = True
        (updated if previous_hash else added).append(relative)

    for relative, previous_hash in sorted(previous_files.items()):
        if relative in upstream_files:
            continue
        if any(relative == blocked or relative.startswith(blocked) for blocked in blocked_paths):
            next_files[relative] = previous_hash
            continue
        destination, path_error = safe_destination(skills_root, relative)
        if path_error:
            conflicts.append(path_error)
            next_files[relative] = previous_hash
            continue
        assert destination is not None
        if not destination.exists():
            continue
        if not destination.is_file() or digest(destination.read_bytes()) != previous_hash:
            conflicts.append(f"{relative}: stale locally modified path was preserved")
            next_files[relative] = previous_hash
            continue
        destination.unlink()
        remove_empty_skill_directories(destination, skills_root)
        removed.append(relative)
        content_changed = True

    manifest_commit = source_commit if content_changed or conflicts or not manifest_path.exists() else previous_commit
    manifest_content = render_manifest(manifest_commit, next_files)
    manifest_changed = not manifest_path.exists() or manifest_path.read_text(encoding="utf-8") != manifest_content
    if manifest_changed:
        manifest_path.parent.mkdir(parents=True, exist_ok=True)
        manifest_path.write_text(manifest_content, encoding="utf-8")

    report = write_report(report_path, source_commit, added, updated, removed, conflicts)
    changed = content_changed or manifest_changed
    if changed:
        print(f"OpenSpec skills synchronized from {source_commit}.")
    else:
        print("No upstream skill changes detected.")
    for conflict in conflicts:
        print(f"Conflict: {conflict}")
    return changed, report


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--upstream-skills", type=Path, required=True)
    parser.add_argument("--commit", required=True)
    parser.add_argument("--repository-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--report", type=Path)
    args = parser.parse_args()

    try:
        changed, _ = synchronize(
            args.repository_root.resolve(),
            args.upstream_skills.resolve(),
            args.commit,
            args.report,
        )
    except (OSError, ValueError) as error:
        parser.error(str(error))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
